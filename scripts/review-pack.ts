/// <reference types="node" />
// Writes docs/review/zone1-sentences.md: generated Zone 1 sentences with their blanks,
// answers and cards, for a native speaker to check. Run with `npm run review-pack`.
// Deterministic: the same content always produces the same file.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zoneTemplates } from '../src/content/deck';
import { BLANK, generate } from '../src/content/generator';
import { DIRECTIONS, type Question } from '../src/content/types';
import { validateBundled } from '../src/content/validate';

const TOTAL = 200;
const MAX_SEED = 100_000;
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../docs/review/zone1-sentences.md');

const errors = validateBundled();
if (errors.length > 0) {
  console.error(`content is invalid:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

function answers(q: Question): string[] {
  return q.strikes.map((s) => s.options[s.correct]);
}

function filled(q: Question): string {
  const a = answers(q);
  return q.sentence
    .split(BLANK)
    .map((part, i) => (i === 0 ? part : (a[i - 1] ?? '') + part))
    .join('');
}

function distractors(q: Question): string {
  return q.strikes
    .map((s) => DIRECTIONS.filter((d) => d !== s.correct).map((d) => s.options[d]).join(', '))
    .join(' / ');
}

const cell = (s: string): string => s.replace(/\|/g, '\\|');

const templates = zoneTemplates(1);
const per = Math.floor(TOTAL / templates.length);
const extra = TOTAL - per * templates.length;

const sections: string[] = [];
let count = 0;
templates.forEach((t, ti) => {
  const want = per + (ti < extra ? 1 : 0);
  const seen = new Set<string>();
  const rows: string[] = [];
  for (let seed = 1; seed <= MAX_SEED && rows.length < want; seed++) {
    const q = generate(t, seed);
    const key = filled(q) + q.prompt;
    if (seen.has(key)) continue;
    seen.add(key);
    rows.push(
      `| ${count + rows.length + 1} | ${seed} | ${cell(q.sentence)} | ${cell(q.prompt ?? '')} | **${cell(answers(q).join(' / '))}** | ${cell(filled(q))} | ${cell(distractors(q))} |`,
    );
  }
  count += rows.length;
  sections.push(
    [
      `## \`${t.id}\` (${t.kind})`,
      '',
      `Pattern: \`${t.pattern}\`${t.gloss_en ? ` · English prompt: \`${t.gloss_en}\`` : ''} · Blanks: ${t.blanks.join(', ')}` +
        (rows.length < want ? ` · only ${rows.length} distinct sentences exist` : ''),
      '',
      '| # | Seed | Shown | Prompt | Answer | Full sentence | Wrong cards |',
      '| --- | --- | --- | --- | --- | --- | --- |',
      ...rows,
    ].join('\n'),
  );
});

const md = `# Zone 1 generated sentences: native-speaker review

Generated by \`npm run review-pack\` from \`src/content/data\`. Do not edit by hand; fix the
lexicon or templates and regenerate. ${count} sentences from ${templates.length} templates. Each row
can be rebuilt in the game from its template id and seed (the \`id#seed\` tag on screen).

## How to review

For each row, check:

1. **Full sentence:** is it grammatical Castilian Spanish (Spain), and is it natural? Mark odd
   but grammatical ones too (for example a mass noun in the plural).
2. **Answer:** is it the only correct choice for the blank?
3. **Wrong cards:** is every one of them really wrong in this sentence? A wrong card that
   could also be right is a serious bug.
4. **Prompt:** for vocabulary and translation rows, does the English match the Spanish?
5. Accents and punctuation (á é í ó ú ñ ü ¿ ¡).

Note a row by its number or its \`template#seed\`.

## Open questions for the reviewer

- \`mirar\` with an animal (\`miro el lobo\`): should it be \`miro al lobo\` (personal *a*)?
  The generator cannot contract \`a el\` yet, so these sentences use \`el\` for now.
- \`sopa\`, \`vino\` and \`leche\` are tagged \`mass\` and kept out of the plural and indefinite
  templates. Is that the right set? Should more nouns have the tag?
- \`unos\` / \`unas\` with plural objects (\`t_indefinite_plural\`): natural, or better avoided?
- English glosses (\`gloss_en\` in lexicon.json and templates.json) were added in milestone 2.
  \`tocar\` is glossed "touch" (also "ring" a bell, "play" an instrument) and \`llevar\` as
  "carry" (also "wear", "take").

${sections.join('\n\n')}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md);
console.log(`wrote ${count} sentences to ${OUT}`);
