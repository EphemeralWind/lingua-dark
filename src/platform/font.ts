// "Hollow 5": the game's original bitmap font (DECISIONS #78). Pure data plus measuring, so it
// can be tested without a browser. Covers printable ASCII, Spanish (á é í ó ú ñ ü ¿ ¡ and the
// capitals) and the UI symbols the game prints. The font test page (font-test.html) and
// font.test.ts prove the coverage.
//
// Every glyph sits in an 11-row box: rows 0-1 hold capital accents, rows 2-8 the 7-row capitals
// (baseline on row 8), rows 9-10 descenders. Lowercase x-height is 5 rows (4-8); lowercase
// accents sit on rows 1-2 with a clear row above the letter.
//
// Glyph strings: rows joined by "|", "#" is ink, anything else is blank. An optional "N:" prefix
// gives the top row (default 2). Advance is width + 1 unless listed in ADVANCE.

