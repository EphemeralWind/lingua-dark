/** Advance overrides: underscores join into one line so "___" reads as a blank. */
const ADVANCE: Record<string, number> = { _: 5 };

export interface Glyph {
  /** First row of `rows` in the 11-row box. */
  top: number;
  width: number;
  /** Ink rows, top to bottom, each `width` long: true is ink. */
  rows: boolean[][];
  advance: number;
}

function parseGlyph(ch: string, src: string): Glyph {
  let top = 2;
  let body = src;
  const m = /^(\d+):/.exec(src);
  if (m) {
    top = Number(m[1]);
    body = src.slice(m[0].length);
  }
  const lines = body.split('|');
  const width = Math.max(...lines.map((l) => l.length));
  const rows = lines.map((l) => Array.from({ length: width }, (_, i) => l[i] === '#'));
  return { top, width, rows, advance: ADVANCE[ch] ?? width + 1 };
}

export const GLYPHS: ReadonlyMap<string, Glyph> = new Map(
  Object.entries({ ...CAPS, ...LOWER, ...DIGITS, ...SPANISH, ...PUNCT, ...SYMBOLS }).map(([ch, src]) => [ch, parseGlyph(ch, src)]),
);

/** Drawn for a character the font lacks: a hollow box, so a gap is visible, never silent. */
export const MISSING: Glyph = parseGlyph('\u0000', '####|#..#|#..#|#..#|#..#|#..#|####');

export function glyphOf(ch: string): Glyph {
  return GLYPHS.get(ch) ?? MISSING;
}

/** Characters the font cannot draw. */
export function missingChars(text: string): string[] {
  return [...new Set([...text].filter((ch) => ch !== '\n' && !GLYPHS.has(ch)))];
}

/** Width of a line in font pixels (no trailing gap). */
export function measureText(text: string): number {
  let w = 0;
  for (const ch of text) w += glyphOf(ch).advance;
  return Math.max(0, w - 1);
}
